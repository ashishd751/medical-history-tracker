/**
 * Attachment rows.
 *
 * The rows themselves are written by `recordRepository` inside the record's transaction — a record
 * with half its attachments would be a record whose detail screen cannot be trusted. This module
 * exposes the pieces so that both the record repository and the future OCR phases share one
 * insert path, and so the startup sweeper can read every stored path.
 */
import { and, eq, inArray } from 'drizzle-orm';

import type { AttachmentRole } from '../../domain';
import { type AppError, appError } from '../../lib/errors';
import { err, ok, type Result } from '../../lib/result';
import type { AppDatabase } from '../db';
import { attachment, type AttachmentRow } from '../schema';

export interface AttachmentInput {
  /**
   * Generated by the caller, not by the repository: the file path contains the id, so the file is
   * already at its final location by the time the row is written.
   */
  readonly id: string;
  readonly role: AttachmentRole;
  readonly mime: string;
  /** Relative to the documents directory. */
  readonly relPath: string;
  readonly thumbRelPath: string | null;
  readonly bytes: number;
  readonly sha256: string;
}

/** The transaction handle Drizzle hands to a synchronous transaction callback. */
type AppTransaction = Parameters<Parameters<AppDatabase['transaction']>[0]>[0];

/**
 * Inserts the rows for one record. Runs inside the caller's transaction, so a failure here rolls
 * the record back too.
 */
export function insertAttachments(
  tx: AppTransaction,
  recordId: string,
  inputs: readonly AttachmentInput[],
  now: number,
): void {
  for (const input of inputs) {
    tx.insert(attachment)
      .values({
        id: input.id,
        recordId,
        role: input.role,
        mime: input.mime,
        relPath: input.relPath,
        thumbRelPath: input.thumbRelPath,
        bytes: input.bytes,
        sha256: input.sha256,
        createdAt: now,
      })
      .run();
  }
}

/** Both stored paths for a row, skipping the optional thumbnail. */
export function attachmentPathsOf(row: {
  readonly relPath: string;
  readonly thumbRelPath: string | null;
}): string[] {
  return row.thumbRelPath ? [row.relPath, row.thumbRelPath] : [row.relPath];
}

export interface AttachmentRepository {
  create(recordId: string, inputs: readonly AttachmentInput[]): Result<true, AppError>;
  listByRecord(recordId: string): AttachmentRow[];
  getById(attachmentId: string): AttachmentRow | null;
  /** Every row, for the startup sweeper. */
  listAll(): AttachmentRow[];
  /**
   * Deletes rows scoped to their record and returns what was removed, so the caller can delete the
   * files after the transaction commits.
   */
  removeMany(recordId: string, ids: readonly string[]): Result<readonly AttachmentRow[], AppError>;
}

export function createAttachmentRepository(
  db: AppDatabase,
  now: () => number = Date.now,
): AttachmentRepository {
  return {
    create(recordId, inputs) {
      if (inputs.length === 0) return ok(true);
      try {
        db.transaction((tx) => insertAttachments(tx, recordId, inputs, now()));
        return ok(true);
      } catch (error) {
        return err(appError('DB_FAILURE', 'Could not save the attachments.', error));
      }
    },

    listByRecord: (recordId) =>
      db.select().from(attachment).where(eq(attachment.recordId, recordId)).all(),

    getById: (attachmentId) =>
      db.select().from(attachment).where(eq(attachment.id, attachmentId)).get() ?? null,

    listAll: () => db.select().from(attachment).all(),

    removeMany(recordId, ids) {
      if (ids.length === 0) return ok([]);
      try {
        let removed: AttachmentRow[] = [];
        db.transaction((tx) => {
          removed = tx
            .select()
            .from(attachment)
            .where(and(eq(attachment.recordId, recordId), inArray(attachment.id, [...ids])))
            .all();
          if (removed.length > 0) {
            tx.delete(attachment)
              .where(and(eq(attachment.recordId, recordId), inArray(attachment.id, [...ids])))
              .run();
          }
        });
        return ok(removed);
      } catch (error) {
        return err(appError('DB_FAILURE', 'Could not remove the attachments.', error));
      }
    },
  };
}
